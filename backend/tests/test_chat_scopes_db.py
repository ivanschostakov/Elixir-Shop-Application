def test_chat_histories_and_mentor_erasure_are_isolated():
    async def run():
        async with database() as (db, user):
            await enable(db, user)
            professor = await create_ai_chat(db, AIChatCreate(user_id=user.id, scope="ordinary", conversation_id="conv_professor_scopes"), commit=False)
            mentor = await dialogue.chat_for(db, user.id)
            assert mentor.id != professor.id and mentor.scope == "mentor"
            professor_message = AIMessage(user_id=user.id, chat_id=professor.id, text="Catalog", sender=MessageSender.USER)
            db.add(professor_message)
            await dialogue.say(db, user.id, "Personal nutrition")
            await db.flush()
            ordinary = await get_ai_chat_by_user_id(db, user.id)
            personal = await get_ai_chat_by_user_id(db, user.id, scope="mentor")
            assert [m.text for m in ordinary.messages] == ["Catalog"]
            assert "Personal nutrition" in [m.text for m in personal.messages]
            assert "Catalog" not in [m.text for m in personal.messages]
            from src.app.modules.users.me.companion import read_messages
            from src.app.modules.users.me.ai_chat import get_my_ai_chat
            assert [m.text for m in (await read_messages(user=user, db=db)).chat.messages] == [m.text for m in personal.messages]
            assert [m.text for m in (await get_my_ai_chat(current_user=user, db=db, _app_integrity=None)).chat.messages] == ["Catalog"]
            await service.register_resource(db, user.id, "conversation", professor.conversation_id, scope="ordinary")
            await service.register_resource(db, user.id, "response", "resp_professor", scope="ordinary")
            await service.register_resource(db, user.id, "file", "file_professor", scope="ordinary")
            await service.register_resource(db, user.id, "response", "resp_mentor")
            await service.erase_companion(db, user.id)
            await db.flush()
            ordinary = await get_ai_chat_by_user_id(db, user.id)
            personal = await get_ai_chat_by_user_id(db, user.id, scope="mentor")
            assert ordinary.conversation_id == "conv_professor_scopes"
            assert [m.text for m in ordinary.messages] == ["Catalog"]
            assert personal.messages == []
            resource = (await db.execute(text("SELECT status FROM ai_provider_resources WHERE external_id = 'conv_professor_scopes'"))).scalar_one()
            assert resource == "active"
            resources = dict((await db.execute(text("SELECT external_id, status FROM ai_provider_resources"))).all())
            assert resources["resp_professor"] == resources["file_professor"] == "active"
            assert resources["resp_mentor"] == "pending_delete"
    asyncio.run(run())


def test_scope_migration_preserves_ids_and_attachments_and_downgrade_preserves_mentor_only_users(monkeypatch):
    async def run():
        engine = create_async_engine(URL, poolclass=NullPool)
        try:
            async with engine.connect() as connection:
                transaction = await connection.begin()
                await connection.execute(text("CREATE SCHEMA chat_scope_migration_test"))
                await connection.execute(text("SET LOCAL search_path TO chat_scope_migration_test"))
                for statement in [
                    "CREATE TABLE users (id bigint PRIMARY KEY)",
                    "CREATE TABLE chats (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id), conversation_id text NOT NULL UNIQUE, current_tokens integer NOT NULL DEFAULT 0, total_tokens integer NOT NULL DEFAULT 0, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now())",
                    "CREATE UNIQUE INDEX ix_chats_user_id ON chats (user_id)",
                    "CREATE TABLE ai_messages (id bigint PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id), chat_id bigint NOT NULL REFERENCES chats(id) ON DELETE CASCADE, is_sensitive boolean NOT NULL DEFAULT false)",
                    "CREATE TABLE attachments (id bigint PRIMARY KEY, message_id bigint NOT NULL REFERENCES ai_messages(id) ON DELETE CASCADE)",
                    "CREATE TABLE ai_provider_resources (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint, kind varchar(24), external_id varchar(200), status varchar(24), attempts integer, next_attempt_at timestamptz, created_at timestamptz, updated_at timestamptz, CONSTRAINT uq_ai_provider_resource UNIQUE(kind, external_id))",
                    "INSERT INTO users VALUES (1),(2),(3)",
                    "INSERT INTO chats (user_id, conversation_id) VALUES (1,'conv_clean'),(2,'conv_mixed')",
                    "INSERT INTO ai_messages VALUES (10,1,1,false),(20,2,2,false),(21,2,2,true)",
                    "INSERT INTO attachments VALUES (99,21)",
                    "INSERT INTO ai_provider_resources (user_id,kind,external_id,status,attempts) VALUES (1,'response','resp_clean','active',0),(2,'response','resp_mixed','active',0)",
                ]:
                    await connection.execute(text(statement))
                path = Path(__file__).resolve().parents[1] / "migrations/versions/a6c8e0f2b4d7_separate_mentor_and_professor_chats.py"
                spec = importlib.util.spec_from_file_location("chat_scope_migration", path)
                migration = importlib.util.module_from_spec(spec); spec.loader.exec_module(migration)
                def migrate(sync, method):
                    monkeypatch.setattr(migration, "op", Operations(MigrationContext.configure(sync)))
                    getattr(migration, method)()
                await connection.run_sync(lambda sync: migrate(sync, "upgrade"))
                rows = (await connection.execute(text("SELECT id, user_id, scope, conversation_id FROM chats ORDER BY id"))).all()
                assert rows[0].conversation_id == "conv_clean"
                assert dict((await connection.execute(text("SELECT external_id, scope FROM ai_provider_resources WHERE kind='response'"))).all()) == {"resp_clean": "ordinary", "resp_mixed": "mentor"}
                assert rows[1].conversation_id.startswith("reset:split:ordinary:")
                mentor = next(row for row in rows if row.scope == "mentor")
                assert (await connection.execute(text("SELECT chat_id FROM ai_messages WHERE id=21"))).scalar_one() == mentor.id
                assert (await connection.execute(text("SELECT chat_id FROM ai_messages WHERE id=20"))).scalar_one() == 2
                assert (await connection.execute(text("SELECT message_id FROM attachments WHERE id=99"))).scalar_one() == 21
                assert (await connection.execute(text("SELECT status FROM ai_provider_resources WHERE external_id='conv_mixed'"))).scalar_one() == "pending_delete"
                await connection.execute(text("INSERT INTO chats (user_id,scope,conversation_id) VALUES (3,'mentor','conv_new_mentor')"))
                await connection.execute(text("INSERT INTO ai_messages SELECT 30,3,id,true FROM chats WHERE user_id=3"))
                await connection.run_sync(lambda sync: migrate(sync, "downgrade"))
                assert (await connection.execute(text("SELECT count(*) FROM chats"))).scalar_one() == 3
                assert (await connection.execute(text("SELECT count(*) FROM ai_messages"))).scalar_one() == 4
                assert (await connection.execute(text("SELECT message_id FROM attachments WHERE id=99"))).scalar_one() == 21
                await transaction.rollback()
        finally:
            await engine.dispose()
    asyncio.run(run())


def test_idempotent_receipt_cannot_cross_chat_scope(monkeypatch):
    from src.app.services.ai import chat as chat_service
    monkeypatch.setattr(chat_service, "require_ai_data_consent", AsyncMock())
    async def run():
        async with database() as (db, user):
            profile = await enable(db, user)
            ordinary = await create_ai_chat(db, AIChatCreate(user_id=user.id, conversation_id="conv_receipt_ordinary"), commit=False)
            mentor = await dialogue.chat_for(db, user.id)
            db.add(AIMessage(user_id=user.id, chat_id=ordinary.id, sender=MessageSender.USER, text="Same text", client_request_id="cross-chat-receipt", context_json={"generation_status": "completed"}))
            await db.flush()
            get_chat = AsyncMock(return_value=mentor)
            monkeypatch.setattr(chat_service, "get_or_create_user_chat", get_chat)
            with pytest.raises(HTTPException) as error:
                await chat_service.send_user_chat_message(db, user=user, text="Same text", attachments=None, professor_client=SimpleNamespace(), companion_profile=profile, dialogue_protocol=2, client_request_id="cross-chat-receipt")
            assert error.value.status_code == 409
            get_chat.assert_awaited_once()
            assert get_chat.await_args.kwargs["scope"] == "mentor"
    asyncio.run(run())
