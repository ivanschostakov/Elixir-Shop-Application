class GuideDocTemplate(BaseDocTemplate):
    def __init__(self, filename: str) -> None:
        super().__init__(
            filename,
            pagesize=A4,
            leftMargin=18 * mm,
            rightMargin=18 * mm,
            topMargin=21 * mm,
            bottomMargin=18 * mm,
            title="Elixir Shop Admin - руководство и описание функционала",
            author="Elixir Shop",
            subject="CRM, роли, поддержка, аналитика, интеграции и эксплуатация",
        )
        frame = Frame(
            self.leftMargin,
            self.bottomMargin,
            self.width,
            self.height,
            id="body",
        )
        self.addPageTemplates(
            PageTemplate(id="guide", frames=[frame], onPage=self._draw_page)
        )

    def _draw_page(self, canvas, doc) -> None:
        page = canvas.getPageNumber()
        canvas.saveState()
        if page > 1:
            canvas.setStrokeColor(LINE)
            canvas.setLineWidth(0.5)
            canvas.line(18 * mm, A4[1] - 13 * mm, A4[0] - 18 * mm, A4[1] - 13 * mm)
            canvas.setFont("ElixirSans", 8)
            canvas.setFillColor(MUTED)
            canvas.drawString(18 * mm, A4[1] - 10 * mm, "ELIXIR SHOP ADMIN")
            canvas.drawRightString(
                A4[0] - 18 * mm,
                A4[1] - 10 * mm,
                "CRM + SALES + OPERATIONS",
            )
        canvas.setFont("ElixirSans", 8)
        canvas.setFillColor(MUTED)
        canvas.drawString(18 * mm, 9 * mm, "Руководство администратора")
        canvas.drawRightString(A4[0] - 18 * mm, 9 * mm, str(page))
        canvas.restoreState()

    def afterFlowable(self, flowable) -> None:
        if not isinstance(flowable, Paragraph):
            return
        style_name = flowable.style.name
        if style_name not in {"H1", "H2"}:
            return
        level = 0 if style_name == "H1" else 1
        text = flowable.getPlainText()
        key = f"section-{self.page}-{abs(hash(text))}"
        self.canv.bookmarkPage(key)
        self.canv.addOutlineEntry(text, key, level=level, closed=False)
        self.notify("TOCEntry", (level, text, self.page, key))


