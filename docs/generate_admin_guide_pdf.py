def p(text: str, style: str = "body") -> Paragraph:
    return Paragraph(text, styles[style])


def h1(text: str) -> Paragraph:
    return p(text, "h1")


def h2(text: str) -> Paragraph:
    return p(text, "h2")


def h3(text: str) -> Paragraph:
    return p(text, "h3")


def bullets(items: list[str]) -> list[Paragraph]:
    return [Paragraph(f"• {item}", styles["bullet"]) for item in items]


def numbers(items: list[str]) -> list[Paragraph]:
    return [
        Paragraph(f"<b>{index}.</b> {item}", styles["number"])
        for index, item in enumerate(items, start=1)
    ]


def callout(title: str, text: str, tone: str = "info") -> Table:
    palette = {
        "info": (TEAL_LIGHT, TEAL),
        "blue": (BLUE_LIGHT, colors.HexColor("#2457A6")),
        "warning": (AMBER_LIGHT, colors.HexColor("#9A5A00")),
        "danger": (RED_LIGHT, colors.HexColor("#B42318")),
    }
    background, accent = palette[tone]
    cell = p(f"<b>{title}</b><br/>{text}", "body")
    table = Table([[cell]], colWidths=[174 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), background),
                ("BOX", (0, 0), (-1, -1), 0.8, accent),
                ("LINEBEFORE", (0, 0), (0, -1), 4, accent),
                ("LEFTPADDING", (0, 0), (-1, -1), 12),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
            ]
        )
    )
    return table


def table(
    rows: list[list[str]],
    widths: list[float],
    *,
    header: bool = True,
    font_size: float = 8.2,
) -> LongTable:
    body_style = ParagraphStyle(
        "TableBody",
        parent=styles["small"],
        fontSize=font_size,
        leading=font_size + 3,
        textColor=INK,
        spaceAfter=0,
    )
    header_style = ParagraphStyle(
        "TableHeader",
        parent=body_style,
        fontName="ElixirSans-Bold",
        textColor=WHITE,
    )
    formatted = []
    for row_index, row in enumerate(rows):
        formatted.append(
            [
                Paragraph(str(value), header_style if header and row_index == 0 else body_style)
                for value in row
            ]
        )
    result = LongTable(
        formatted,
        colWidths=widths,
        repeatRows=1 if header else 0,
        hAlign="LEFT",
    )
    commands = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, colors.HexColor("#FAFBFC")]),
    ]
    if header:
        commands.append(("BACKGROUND", (0, 0), (-1, 0), TEAL))
    result.setStyle(TableStyle(commands))
    return result


