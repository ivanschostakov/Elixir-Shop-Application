export function domainLabel(value: string | null | undefined, locale: Locale): string {
  if (value === null || value === undefined) return "—"
  if (value === "") return value
  const original = value.trim()
  const normalized = original.toLowerCase()
  if (labels[normalized]) return labels[normalized][locale]
  const actionParts = normalized.split(".")
  if (
    actionParts.length > 1
    && actionParts.every((part) => Boolean(actionTokens[part] || labels[part]))
  ) {
    return actionParts
      .map((part) => actionTokens[part]?.[locale] || labels[part]?.[locale])
      .join(" · ")
  }
  return value
}

