export function mentorText(source: string, values: readonly unknown[] = [], language: Language = getTranslationLanguage()): string {
    const key = source.trim()
    const phrase = language === "ru" ? source : mentorTranslations[key]?.[language]
    const translated = phrase === undefined ? source : language === "ru" ? phrase : source.slice(0, source.indexOf(key)) + phrase.trim() + source.slice(source.indexOf(key) + key.length)
    return translated.replace(/\{(\d+)\}/g, (placeholder, index) => Number(index) < values.length ? String(values[Number(index)] ?? "") : placeholder)
}

export function mentorLocale(language: Language = getTranslationLanguage()): string {
    return language === "kz" ? "kk-KZ" : language === "en" ? "en-US" : "ru-RU"
}

// Some phone/browser ICU bundles recognize kk-KZ but omit its month names.
const kazakhMonths = ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан", "қараша", "желтоқсан"]
const kazakhShortMonths = ["қаң", "ақп", "нау", "сәу", "мам", "мау", "шіл", "там", "қыр", "қаз", "қар", "жел"]
export function mentorDateLabel(value: Date, options?: Intl.DateTimeFormatOptions, language: Language = getTranslationLanguage()): string {
    if (language !== "kz") return value.toLocaleDateString(mentorLocale(language), options)
    const format = options ?? { year: "numeric", month: "2-digit", day: "2-digit" }
    const day = format.day ? String(value.getDate()).padStart(format.day === "2-digit" ? 2 : 1, "0") : ""
    const year = format.year ? String(value.getFullYear()) : ""
    const month = format.month === "long" ? kazakhMonths[value.getMonth()] : format.month === "short" ? kazakhShortMonths[value.getMonth()] : format.month ? String(value.getMonth() + 1).padStart(format.month === "2-digit" ? 2 : 1, "0") : ""
    if (format.month === "long" || format.month === "short") return [day, month, year ? `${year} ж.` : ""].filter(Boolean).join(" ")
    return [day, month, year].filter(Boolean).join(".")
}

export function mentorDateTimeLabel(value: Date, timeZone: string, language: Language = getTranslationLanguage()): string {
    if (language !== "kz") return value.toLocaleString(mentorLocale(language), { timeZone, hourCycle: "h23" })
    const parts = new Intl.DateTimeFormat("en-GB", { timeZone, year: "numeric", month: "2-digit", day: "2-digit", hour: "2-digit", minute: "2-digit", second: "2-digit", hourCycle: "h23" }).formatToParts(value)
    const fields = Object.fromEntries(parts.map(part => [part.type, part.value]))
    return `${fields.day}.${fields.month}.${fields.year}, ${fields.hour}:${fields.minute}:${fields.second}`
}
